from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[2]
s=json.loads((ROOT/'spec/det/registers.json').read_text())
h=['/* Generated by scripts/det/gen_spec.py. */','#ifndef DET_SPEC_H','#define DET_SPEC_H',f'#define DET_BASE 0x{s["base"]:08x}u',f'#define DET_VERSION 0x{s["version"]:08x}u']
v=['// Generated by scripts/det/gen_spec.py.',f'localparam [31:0] DET_INTERFACE_VERSION=32\'h{s["version"]:08x};']
for k,val in s['registers'].items():
 h.append(f'#define DET_REG_{k} {val}u');v.append(f'localparam [7:0] REG_{k}=8\'d{val};')
for key,pre in [('descriptor','D'),('fusion','F')]:
 for i,k in enumerate(s[key]):
  if k.startswith('RESERVED') and k != 'RESERVED': continue
  h.append(f'#define {pre}_{k} {i}u');v.append(f'localparam integer {pre}_{k}={i};')
h+=['#endif','']
(ROOT/'firmware/det/spec.h').write_text('\n'.join(h))
(ROOT/'rtl/det/spec.vh').write_text('\n'.join(v)+'\n')
